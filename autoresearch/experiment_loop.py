"""
experiment_loop.py — Autoresearch-style routing optimizer for LibraryOfBabel

USAGE:
    cd /Users/weixiangzhang/Local_Dev/projects/LibraryOfBabel/autoresearch
    python experiment_loop.py

    # Run at most N experiments (default: unlimited)
    python experiment_loop.py --max-experiments 10

    # Reset state and start over from hypothesis 0
    python experiment_loop.py --reset

    # Dry-run: evaluate current routing_config without advancing
    python experiment_loop.py --eval-only

PROTOCOL:
    1. Load state (last best recall, next hypothesis index)
    2. Apply next hypothesis from hypothesis_space.py → write routing_config.py
    3. Run evaluator.evaluate() → get Recall@K
    4. Compare against best recall so far:
         - Improved (or equal with simpler config): KEEP, record in results.tsv
         - Regressed: REVERT routing_config.py to best snapshot
    5. Advance hypothesis index, goto 2
    6. Stop when all hypotheses exhausted or --max-experiments reached
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).parent

ROUTING_CONFIG  = HERE / "routing_config.py"
BEST_SNAPSHOT   = HERE / "_best_routing_config.py"
STATE_FILE      = HERE / "state.json"
RESULTS_TSV     = HERE / "results.tsv"


# ── state helpers ─────────────────────────────────────────────────────────────

def load_state() -> dict:
    if STATE_FILE.exists():
        return json.loads(STATE_FILE.read_text())
    return {
        "best_recall":    0.0,
        "best_weighted":  0.0,
        "best_hypothesis": "none",
        "next_index":     0,
        "experiments_run": 0,
        "started":        datetime.now().isoformat(),
    }


def save_state(state: dict):
    STATE_FILE.write_text(json.dumps(state, indent=2))


# ── results.tsv ───────────────────────────────────────────────────────────────

def init_results():
    if not RESULTS_TSV.exists():
        RESULTS_TSV.write_text(
            "index\tname\tdescription\trecall_at_k\tweighted_recall\tk\thits\tn_pairs"
            "\tmodel_usage\tduration_s\tdecision\ttimestamp\n"
        )


def append_result(idx: int, hyp: dict, metrics: dict, decision: str):
    row = "\t".join([
        str(idx),
        hyp["name"],
        hyp["description"].replace("\t", " "),
        str(metrics["recall_at_k"]),
        str(metrics["weighted_recall"]),
        str(metrics["k"]),
        str(metrics["hits"]),
        str(metrics["n_pairs"]),
        json.dumps(metrics["model_usage"]),
        str(metrics["duration_s"]),
        decision,
        datetime.now().isoformat(),
    ])
    with RESULTS_TSV.open("a") as f:
        f.write(row + "\n")


# ── config writer ─────────────────────────────────────────────────────────────

