def write_config(hyp: dict):
    content = TEMPLATE.format(
        name=hyp["name"],
        MODEL_MAPPING=hyp["MODEL_MAPPING"],
        CLASSIFICATION_STRATEGY=hyp["CLASSIFICATION_STRATEGY"],
        TECHNICAL_THRESHOLD=hyp["TECHNICAL_THRESHOLD"],
        NARRATIVE_THRESHOLD=hyp["NARRATIVE_THRESHOLD"],
        CULTURAL_THRESHOLD=hyp["CULTURAL_THRESHOLD"],
        RECALL_K=hyp["RECALL_K"],
    )
    ROUTING_CONFIG.write_text(content)


# ── main loop ─────────────────────────────────────────────────────────────────

def run(max_experiments: int = 0):
    # Late import so evaluator uses the (possibly just-written) routing_config
    sys.path.insert(0, str(HERE))
    from evaluator import evaluate, check_ollama, check_db
    from hypothesis_space import HYPOTHESES

    print("Checking prerequisites...")
    if not check_ollama():
        print("ERROR: Ollama is not running. Start with: ollama serve")
        sys.exit(1)
    if not check_db():
        print("ERROR: Cannot connect to knowledge_base PostgreSQL")
        sys.exit(1)
    print("OK\n")

    init_results()
    state = load_state()
    n     = state["next_index"]
    total = len(HYPOTHESES)

    if n >= total:
        print(f"All {total} hypotheses exhausted.")
        print(f"Best recall: {state['best_recall']} ({state['best_hypothesis']})")
        return

    experiments_this_run = 0

    while n < total:
        if max_experiments > 0 and experiments_this_run >= max_experiments:
            print(f"\nReached --max-experiments {max_experiments}. Stopping.")
            break

        hyp = HYPOTHESES[n]
        print(f"\n{'='*70}")
        print(f"Experiment {n+1}/{total}: {hyp['name']}")
        print(f"  {hyp['description']}")
        print(f"  Strategy={hyp['CLASSIFICATION_STRATEGY']}  K={hyp['RECALL_K']}")
        print(f"  Mapping: {hyp['MODEL_MAPPING']}")
        print(f"  Best so far: {state['best_recall']:.4f} ({state['best_hypothesis']})")

        # snapshot current best before overwriting
        if ROUTING_CONFIG.exists():
            shutil.copy(ROUTING_CONFIG, BEST_SNAPSHOT)

        # apply hypothesis
        write_config(hyp)
        time.sleep(0.5)  # let filesystem settle

        # evaluate
        try:
            metrics = evaluate(verbose=True)
        except Exception as e:
            print(f"  ERROR during evaluation: {e}")
            # revert
            if BEST_SNAPSHOT.exists():
                shutil.copy(BEST_SNAPSHOT, ROUTING_CONFIG)
            append_result(n, hyp, {"recall_at_k": 0.0, "weighted_recall": 0.0,
                                    "k": hyp["RECALL_K"], "hits": 0, "n_pairs": 0,
                                    "model_usage": {}, "duration_s": 0.0}, "error")
            n += 1
            state["next_index"] = n
            state["experiments_run"] += 1
            save_state(state)
            experiments_this_run += 1
            continue

        recall   = metrics["recall_at_k"]
        w_recall = metrics["weighted_recall"]
        improved = recall > state["best_recall"]
        tied     = recall == state["best_recall"]

        if improved:
            decision = "keep"
            state["best_recall"]    = recall
            state["best_weighted"]  = w_recall
            state["best_hypothesis"] = hyp["name"]
            # keep the written routing_config as-is
        else:
            decision = "revert"
            # restore previous best
            if BEST_SNAPSHOT.exists():
                shutil.copy(BEST_SNAPSHOT, ROUTING_CONFIG)

        print(f"\n  Recall@{metrics['k']}: {recall:.4f}  (weighted: {w_recall:.4f})")
        print(f"  Duration: {metrics['duration_s']}s")
        print(f"  Decision: {decision.upper()}")

        append_result(n, hyp, metrics, decision)

        n += 1
        state["next_index"]     = n
        state["experiments_run"] += 1
        save_state(state)
        experiments_this_run += 1

    print(f"\n{'='*70}")
    print(f"Run complete. {experiments_this_run} experiments this session.")
    print(f"Best recall: {state['best_recall']:.4f} ({state['best_hypothesis']})")
    print(f"Results written to: {RESULTS_TSV}")


# ── CLI ───────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description="LibraryOfBabel routing autoresearch loop")
    parser.add_argument("--max-experiments", type=int, default=0,
                        help="Stop after N experiments (0 = unlimited)")
    parser.add_argument("--reset", action="store_true",
                        help="Delete state.json and start from hypothesis 0")
    parser.add_argument("--eval-only", action="store_true",
                        help="Evaluate current routing_config without advancing state")
    args = parser.parse_args()

    if args.reset:
        for f in [STATE_FILE, BEST_SNAPSHOT]:
            if f.exists():
                f.unlink()
        print("State reset. Starting from hypothesis 0.\n")

    if args.eval_only:
        sys.path.insert(0, str(HERE))
        from evaluator import evaluate, check_ollama, check_db
        if not check_ollama() or not check_db():
            sys.exit(1)
        m = evaluate(verbose=True)
        print(f"\nRecall@{m['k']}: {m['recall_at_k']:.4f}  weighted: {m['weighted_recall']:.4f}")
        print(f"Hits: {m['hits']}/{m['n_pairs']}  models: {m['model_usage']}")
        return

    run(max_experiments=args.max_experiments)


if __name__ == "__main__":
    main()
